import json

# Функция, которая читает готовый результат из файла и показывает его пользователю
def load_and_display(filename="matrix_data.json"):
    # Блок try-except нужен для обработки исключительных ситуаций (защита от падений)
    try:
        # Открываем файл для чтения ("r"). Кодировка utf-8 нужна для русского текста.
        with open(filename, "r", encoding="utf-8") as f:
            # Загружаем данные из JSON-файла в переменную data (превращаем в словарь Python)
            data = json.load(f)

        # Достаем вектор по ключу "vector_b" и выводим его на экран
        print(f"Модуль вывода: Итоговый вектор B -> {data['vector_b']}")

    # Если файл с данными не найден, выполняется этот блок
    except FileNotFoundError:
        # Выводим сообщение об ошибке, чтобы программа не вылетала
        print("Модуль вывода: Ошибка! Файл с данными не найден.")
