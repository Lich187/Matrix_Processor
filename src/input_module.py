import json

# Функция для получения исходных данных (в реальности тут был бы ввод с клавиатуры)
def get_input_matrix():
    # Имитируем ввод данных: возвращаем тестовую матрицу 3x3
    return [[2, 2, 2], [1, 2, 3], [5, 2, 1]]

# Функция сохранения матрицы, чтобы передать её следующему модулю через файл
def save_input_to_json(matrix, filename="matrix_data.json"):
    # Открываем файл для записи ("w"), чтобы передать матрицу следующему модулю
    with open(filename, "w", encoding="utf-8") as f:
        # Записываем данные в формате JSON, добавляя ключ "matrix" и метку этапа
        json.dump({"matrix": matrix, "stage": "input"}, f)
    # Выводим сообщение в консоль для подтверждения успешного сохранения
    print("Модуль ввода: Матрица сохранена в JSON.")
